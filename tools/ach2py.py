"""Convert upstream server/achievements.ts into data/achievement_data.py (conditions as (key, min) lists)."""
import json, re, sys
src = open(sys.argv[1]).read()
body = src[src.index("export const ACHIEVEMENTS"):src.index("export interface UnlockedAchievement")]
out = []
for m in re.finditer(r'\{\s*id: "([^"]+)",\s*name: "((?:[^"\\]|\\.)*)",\s*description: "((?:[^"\\]|\\.)*)",\s*icon: "((?:[^"\\]|\\.)*)",\s*check: (.*?),\s*secret: (true|false),', body, re.S):
    i, n, d, ic, chk, sec = m.groups()
    dec = lambda s: json.loads(f'"{s}"')
    if chk.strip() == "() => true":
        conds = []
    elif "ACHIEVEMENTS.length" in chk:
        k = re.search(r">= ACHIEVEMENTS.length - (\d+)", chk).group(1)
        conds = [["achievements_unlocked", len(re.findall(r"^    id: ", body, re.M)) - int(k)]]
    else:
        conds = [[a, int(b)] for a, b in re.findall(r"e\.(\w+) >= (\d+)", chk)]
        assert conds and chk.count("e.") == len(conds), (i, chk)
    out.append((i, dec(n), dec(d), dec(ic), conds, sec == "true"))
print(len(out), file=sys.stderr)
with open(sys.argv[2], "w") as f:
    f.write('"""Generated by tools/ach2py.py from coding-buddy server/achievements.ts (MIT). Do not edit."""\n\n')
    f.write("# (id, name, description, icon, [(counter, minimum), ...] all required, secret)\nACHIEVEMENTS = [\n")
    for r in out:
        f.write("    " + repr(tuple(r)) + ",\n")
    f.write("]\n")
