#!/usr/bin/env python3
"""Convert plain TypeScript object/array literals into Python data.

goose-buddy reuses the species art and reaction pools of coding-buddy (MIT). Rather than
re-typing hundreds of strings by hand, this tool lifts the literals out of the upstream
source mechanically and writes Python modules. It understands only what those files use:
strings, numbers, true/false/null, arrays, objects with bare or quoted keys, comments.

    python tools/ts2py.py /path/to/coding-buddy
"""

from __future__ import annotations

import ast
import pprint
import re
import sys
from pathlib import Path

_IDENT = re.compile(r"[A-Za-z_$][\w$-]*")


def find_literal(src: str, name: str) -> str:
    """Return the text of the {...} or [...] literal assigned to `const <name>`."""
    m = re.search(rf"(?:export\s+)?const\s+{re.escape(name)}\b[^=]*?=\s*(?=[\[{{])", src)
    if not m:
        raise KeyError(name)
    start = m.end()
    opener = src[start]
    closer = "}" if opener == "{" else "]"
    depth, i, in_str = 0, start, None
    while i < len(src):
        c = src[i]
        if in_str:
            if c == "\\":
                i += 2
                continue
            if c == in_str:
                in_str = None
        elif c in "\"'`":
            in_str = c
        elif src.startswith("//", i):
            i = src.index("\n", i)
            continue
        elif src.startswith("/*", i):
            i = src.index("*/", i) + 2
            continue
        elif c in "{[":
            depth += 1
        elif c in "}]":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1
    raise ValueError(f"unterminated literal for {name}")


def to_python_source(lit: str) -> str:
    """Rewrite a TS literal as Python source (quote bare keys, drop comments, map keywords)."""
    out: list[str] = []
    i, n = 0, len(lit)
    while i < n:
        c = lit[i]
        if c in "\"'":
            j = i + 1
            while j < n and lit[j] != c:
                j += 2 if lit[j] == "\\" else 1
            body = lit[i + 1:j]
            out.append(repr(_unescape(body, c)))
            i = j + 1
        elif lit.startswith("//", i):
            i = lit.index("\n", i) if "\n" in lit[i:] else n
        elif lit.startswith("/*", i):
            i = lit.index("*/", i) + 2
        elif c.isalpha() or c in "_$":
            m = _IDENT.match(lit, i)
            word = m.group(0)
            j = m.end()
            k = j
            while k < n and lit[k] in " \t\r\n":
                k += 1
            if k < n and lit[k] == ":":
                out.append(repr(word))
            else:
                out.append({"true": "True", "false": "False", "null": "None"}.get(word, word))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _unescape(body: str, quote: str) -> str:
    """Decode a JS string body (\\u escapes, \\\\, \\", \\n ...) into the real string."""
    res, i = [], 0
    simple = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"', "'": "'", "`": "`", "0": "\0"}
    while i < len(body):
        c = body[i]
        if c != "\\":
            res.append(c)
            i += 1
            continue
        nxt = body[i + 1]
        if nxt == "u":
            if body[i + 2] == "{":
                end = body.index("}", i)
                res.append(chr(int(body[i + 3:end], 16)))
                i = end + 1
            else:
                res.append(chr(int(body[i + 2:i + 6], 16)))
                i += 6
        elif nxt == "x":
            res.append(chr(int(body[i + 2:i + 4], 16)))
            i += 4
        else:
            res.append(simple.get(nxt, nxt))
            i += 2
    return "".join(res)


def load(src: str, name: str):
    return ast.literal_eval(to_python_source(find_literal(src, name)))


def emit(path: Path, header: str, values: dict[str, object]) -> None:
    lines = [header.rstrip() + "\n"]
    for key, value in values.items():
        lines.append(f"{key} = " + pprint.pformat(value, width=110, sort_dicts=False) + "\n")
    path.write_text("\n".join(lines))
    print(f"wrote {path} ({len(values)} constants)")


HEADER = '''"""GENERATED by tools/ts2py.py from coding-buddy ({source}). Do not edit by hand.

coding-buddy is MIT licensed, Copyright (c) 2026 coding-buddy contributors; see NOTICE.
"""
'''


def main(upstream: str) -> None:
    root = Path(upstream)
    out = Path(__file__).resolve().parent.parent / "src" / "goose_buddy" / "data"
    art = (root / "core" / "art-data.ts").read_text()
    emit(out / "art_data.py", HEADER.format(source="core/art-data.ts"),
         {"SPECIES_ART": load(art, "SPECIES_ART"), "HAT_ART": load(art, "HAT_ART")})
    eng = (root / "core" / "engine.ts").read_text()
    emit(out / "engine_data.py", HEADER.format(source="core/engine.ts"),
         {k: load(eng, k) for k in ("PEAK_PHRASES", "DUMP_PHRASES", "RARITY_CLOSER", "FACE_TEMPLATES")})
    rx = (root / "core" / "reactions.ts").read_text()
    names = ["NAME_REACTIONS", "DEFAULT_NAME_REACTIONS", "SUCCESS_REACTIONS", "DEFAULT_SUCCESS_REACTIONS",
             "REACTIONS", "SPECIES_REACTIONS", "SNARK_OVERRIDES", "CHAOS_OVERRIDES", "PATIENCE_OVERRIDES",
             "DEBUGGING_OVERRIDES", "WISDOM_OVERRIDES", "RARITY_FLAIR", "ESCALATION_REACTIONS",
             "REASON_TO_COUNTER", "RARITY_BONUS", "FALLBACK_NAMES", "VIBE_WORDS"]
    emit(out / "reaction_data.py", HEADER.format(source="core/reactions.ts"), {k: load(rx, k) for k in names})


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
